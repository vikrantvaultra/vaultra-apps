// Writes data/schemes/_generated.ts: one import per scheme file, so adding a scheme is just adding a file.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../data/schemes/", import.meta.url));

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return walk(p);
    return name.endsWith(".ts") && !name.startsWith("_") && name !== "index.ts" ? [p] : [];
  });
}

const files = walk(root)
  .map((p) => relative(root, p).replace(/\\/g, "/").replace(/\.ts$/, ""))
  .sort();

const ident = (_, i) => `s${i}`;
const out = `// AUTO-GENERATED by scripts/gen-scheme-index.mjs. Do not edit; add or remove scheme files instead.
import type { Scheme } from "@/lib/types";
${files.map((f, i) => `import ${ident(f, i)} from "./${f}";`).join("\n")}

export const SCHEME_FILES: Scheme[] = [${files.map(ident).join(", ")}];
`;

writeFileSync(join(root, "_generated.ts"), out);
console.log(`scheme index: ${files.length} schemes`);
